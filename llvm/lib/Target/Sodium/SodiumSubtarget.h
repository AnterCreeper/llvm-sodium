#ifndef LLVM_SODIUM_SODIUMSUBTARGET_H
#define LLVM_SODIUM_SODIUMSUBTARGET_H

#include "Sodium.h"
#include "SodiumInstrInfo.h"
#include "SodiumISelLowering.h"
#include "SodiumFrameLowering.h"
#include "SodiumRegisterInfo.h"
#include "llvm/CodeGen/GlobalISel/CallLowering.h"
#include "llvm/CodeGen/GlobalISel/InstructionSelector.h"
#include "llvm/CodeGen/GlobalISel/LegalizerInfo.h"
#include "llvm/CodeGen/RegisterBankInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "SodiumGenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class SodiumSubtarget : public SodiumGenSubtargetInfo {
private:
  virtual void anchor();
  MVT XLenVT = MVT::i16;

//declare subtarget feature variable
#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER)                    \
  bool ATTRIBUTE = DEFAULT;
#include "SodiumGenSubtargetInfo.inc"

  SodiumTargetLowering TLInfo;
  SodiumFrameLowering FrameLowering;
  SodiumInstrInfo InstrInfo;
  SodiumRegisterInfo RegInfo;
  SelectionDAGTargetInfo TSInfo;

  /// Initializes using the passed in CPU and feature strings so that we can
  /// use initializer lists for subtarget initialization.
  SodiumSubtarget &initializeSubtargetDependencies(const Triple &TT,
                                                   StringRef CPU,
                                                   StringRef TuneCPU,
                                                   StringRef FS);

public:
  bool is32Bit;

  // Initializes the data members to match that of the specified triple.
  SodiumSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                  StringRef FS, const SodiumTargetMachine &TM);
  ~SodiumSubtarget() override {};

  // Parses features string setting specified subtarget options. The
  // definition of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
  const SodiumTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SodiumFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const SodiumInstrInfo *getInstrInfo() const override {
    return &InstrInfo;
  }
  const SodiumRegisterInfo *getRegisterInfo() const override {
    return &RegInfo;
  }
  bool enableSubRegLiveness() const override { return true; }
  bool enableMachineScheduler() const override { return true; }

protected:

};
} // End llvm namespace

#endif

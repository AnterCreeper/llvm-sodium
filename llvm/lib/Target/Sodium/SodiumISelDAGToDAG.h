#ifndef LLVM_SODIUM_SODIUMISELDAGTODAG_H
#define LLVM_SODIUM_SODIUMISELDAGTODAG_H

#include "Sodium.h"
#include "SodiumTargetMachine.h"
#include "llvm/CodeGen/SelectionDAGISel.h"

// Sodium specific code to select Sodium machine instructions for
// SelectionDAG operations.
namespace llvm {
class SodiumDAGToDAGISel : public SelectionDAGISel {
  const SodiumSubtarget *Subtarget = nullptr;

public:
  static char ID;
  SodiumDAGToDAGISel() = delete;
  explicit SodiumDAGToDAGISel(SodiumTargetMachine &TargetMachine,
                              CodeGenOpt::Level OptLevel)
  : SelectionDAGISel(ID, TargetMachine, OptLevel) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<SodiumSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *Node) override;

#include "SodiumComplexPattern.h"

// Include the pieces autogenerated from the target description.
#include "SodiumGenDAGISel.inc"

private:
  bool tryBitfieldExtractOpfromAND(SelectionDAG *CurDAG, SDNode *Node);
  bool tryBitfieldExtractOpfromSExtInReg(SelectionDAG *CurDAG, SDNode *Node);
  bool tryBitfieldExtractOpfromSHR(SelectionDAG *CurDAG, SDNode *Node,
                                   bool isSigned);
  bool tryBitfieldPack(SelectionDAG *CurDAG, SDNode *Node);
  bool tryShrinkShlLogicImm(SelectionDAG *CurDAG, SDNode *Node, unsigned BinOpc);
  bool tryBitfieldPackfromOrSHL(SelectionDAG *CurDAG, SDNode *Node);
};
} // end namespace llvm

#endif // LLVM_SODIUM_SODIUMISELDAGTODAG_H
